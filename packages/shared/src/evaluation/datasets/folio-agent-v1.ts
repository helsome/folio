//   - tool loop when the news feed returns empty
//   - P/E (or other valuation ratio) fabricated from quote data
//   - intraday tool used when a multi-month kline range was requested
//   - duplicate quote call instead of one tool call
//   - portfolio summary ignored in favor of a single holding quote
